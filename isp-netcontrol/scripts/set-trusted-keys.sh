#!/usr/bin/env bash
# Builds the License Manager's public signing key(s) into ISP NetControl.
#
# Run this once after installing the License Manager, and before building or
# installing ISP NetControl for customers:
#
#   scripts/set-trusted-keys.sh https://licenses.example.com     # fetch from the License Manager
#   scripts/set-trusted-keys.sh /path/to/public-keys.pem         # or use a saved copy
#
# The keys are public: they can verify licenses but never create them.
# After a key rotation in the License Manager you do NOT need to re-run this:
# deployed servers learn the new key through the signed endorsement chain.
# Re-running it is still recommended for new releases.
set -euo pipefail

usage() { echo "usage: $0 <license-server-url | public-keys.pem> [--cacert <ca.pem>]" >&2; exit 2; }
[ $# -ge 1 ] || usage
SRC="$1"; shift
CA=""
if [ "${1:-}" = "--cacert" ]; then CA="${2:-}"; [ -n "$CA" ] || usage; fi

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$HERE/../internal/license/trusted_keys.go"

if [[ "$SRC" =~ ^https?:// ]]; then
  URL="${SRC%/}/api/v1/public-keys"
  CURL=(curl -fsS --max-time 20)
  [ -n "$CA" ] && CURL+=(--cacert "$CA")
  PEM="$("${CURL[@]}" "$URL")" || { echo "error: could not download $URL" >&2; exit 1; }
else
  [ -f "$SRC" ] || { echo "error: $SRC not found" >&2; exit 1; }
  PEM="$(cat "$SRC")"
fi

if ! grep -q -- "-----BEGIN MYDNS LICENSE SIGNING KEY-----" <<<"$PEM"; then
  echo "error: no MYDNS LICENSE SIGNING KEY block found in $SRC" >&2
  exit 1
fi
if grep -q '`' <<<"$PEM"; then
  echo "error: unexpected character in key data" >&2
  exit 1
fi

TMP="$(mktemp)"
{
  echo "package license"
  echo
  echo "// builtinTrustedKeys holds the License Manager's public signing key(s)."
  echo "//"
  echo "// Code generated by scripts/set-trusted-keys.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). DO NOT EDIT."
  echo "const builtinTrustedKeys = \`$PEM"
  echo "\`"
} >"$TMP"
mv "$TMP" "$OUT"
echo "Trusted keys written to $OUT:"
grep "Key-ID" <<<"$PEM" | sed 's/^/  /'
